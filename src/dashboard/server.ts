export function startDashboard(
  container: Container,
  registry: ToolRegistry,
  opts: DashboardOptions,
): HttpServer {
  // Auth is enforced only when bound to a non-loopback address, unless the
  // caller explicitly requires it (control plane with --auth token|api-key).
  const requireAuth = opts.requireAuth ?? !isLoopbackHost(opts.host);
  if (requireAuth && !opts.token) {
    throw new Error("Dashboard bound to a non-loopback host requires a token");
  }

  const sshOperatorWebSessions = opts.sshOperatorBroker
    ? new SshOperatorWebSessions(opts.sshOperatorBroker) : null;
  const server = createServer((req, res) => {
    const credential = extractDashboardCredential(req);
    if (
      requireAuth &&
      (!credential || !timingSafeEqualStr(credential, opts.token!))
    ) {
      res.writeHead(401, {
        "content-type": "application/json; charset=utf-8",
        "www-authenticate": 'Bearer realm="folderforge-dashboard"',
      });
      res.end(
        JSON.stringify({
          error: "unauthorized",
          message: "Valid bearer token required.",
        }),
      );
      return;
    }
    if (sshOperatorWebSessions?.isRoute(req)) {
      // This route never recognizes ordinary Dashboard credentials as SSH
      // authority. The proof must come from a live server-owned SSH lease.
      sshOperatorWebSessions.handle(req, res).catch((err) => {
        logger.error({ err: String(err) }, "SSH operator session request failed");
        if (!res.headersSent) sendJson(res, 500, { error: 'SSH_SESSION_INTERNAL_ERROR' });
      });
      return;
    }
    const principal = dashboardPrincipal(req, credential, requireAuth);
    handle(req, res, container, registry, principal, opts, sshOperatorWebSessions).catch((err) => {
      logger.error({ err: String(err) }, "Dashboard request failed");
      sendJson(res, 500, { error: "internal_error", message: String(err) });
    });
  });

  server.listen(opts.port, opts.host, () => {
    logger.info(
      { host: opts.host, port: opts.port, authRequired: requireAuth },
      "Dashboard listening",
    );
  });

  return server;
}

/**
 * Accept the credential via `Authorization: Bearer <cred>`, an `X-API-Key`
 * header (api-key mode), or a `?token=` query parameter (handy for opening the
 * dashboard in a browser). Comparison is constant-time to avoid leaking the
 * credential length/prefix via timing.
 */
function extractDashboardCredential(req: IncomingMessage): string | undefined {
  const header = req.headers["authorization"];
  if (typeof header === "string" && header.startsWith("Bearer ")) {
    const credential = header.slice("Bearer ".length).trim();
    if (credential) return credential;
  }
  // `api-key` mode: the same credential delivered via the X-API-Key header.
  const apiKey = req.headers["x-api-key"];
  if (typeof apiKey === "string" && apiKey.trim()) return apiKey.trim();
  const url = new URL(req.url ?? "/", "http://localhost");
  return url.searchParams.get("token") ?? undefined;
}

/**
 * Preserve remote client/session/task correlation on dashboard API calls.
 * These headers are metadata only; authentication still comes from the
 * dashboard credential. Invalid or oversized values are ignored rather than
 * becoming durable binding keys.
 */
function dashboardPrincipal(
  req: IncomingMessage,
  credential: string | undefined,
  requireAuth: boolean,
): ToolPrincipal {
  const base = adminPrincipalFromCredential(
    requireAuth ? credential : undefined,
  );
  const clientId = dashboardContextHeader(req, "x-client-id");
  const sessionId = dashboardContextHeader(req, "x-session-id");
  const taskId = dashboardContextHeader(req, "x-task-id");
  return {
    ...base,
    ...(clientId ? { oauthClientId: clientId } : {}),
    ...(sessionId ? { sessionId } : {}),
    ...(taskId ? { taskId } : {}),
  };
}

function dashboardContextHeader(
  req: IncomingMessage,
  name: string,
): string | undefined {
  const value = req.headers[name];
  if (typeof value !== "string") return undefined;
  const normalized = value.trim();
  return normalized.length > 0 && normalized.length <= 256
    ? normalized
    : undefined;
}

/** All directories the operator lets this control plane govern (resolved). */
function fsAllowedRoots(container: Container): string[] {
  const dirs = container.config.workspace.allowedDirectories ?? [];
  if (dirs.length > 0) return dirs.map((d) => resolve(d));
  try {
    return [defaultBrowsePoint()];
  } catch {
    return [container.projectRoot()];
  }
}

/** Display root for the SPA picker: the primary governable directory. */
function fsBrowsePoint(container: Container): string {
  return fsAllowedRoots(container)[0] ?? container.projectRoot();
}

/** Best-effort default: ~/Desktop when it exists, else the home directory. */
function defaultBrowsePoint(): string {
  const desktop = join(homedir(), "Desktop");
  return existsSync(desktop) && statSync(desktop).isDirectory()
    ? desktop
    : homedir();
}

/** True when `target` equals or sits inside `root`. */
function isWithinDir(root: string, target: string): boolean {
  const from = resolve(root);
  const to = resolve(target);
  return to === from || to.startsWith(from + sep);
}

/**
 * Serve the Mission Control SPA (built from packages/mission-control) under
 * /app. Prefers the packaged build output (dist/dashboard/app) and falls back
 * to the in-repo package dist when running from a checkout. 404 with build
 * instructions when the SPA has not been built.
 */
function serveMissionControlApp(res: ServerResponse, path: string): void {
  const relative =
    path === "/app" || path === "/app/"
      ? "index.html"
      : path.slice("/app/".length);
  if (relative.includes("..")) {
    res.writeHead(400, { "content-type": "text/plain" });
    res.end("bad path");
    return;
  }
  const roots = [
    join(__dirname, "app"),
    join(process.cwd(), "packages", "mission-control", "dist"),
  ];
  for (const rootDir of roots) {
    const file = join(rootDir, relative);
    if (existsSync(file) && statSync(file).isFile()) {
      const type = relative.endsWith(".js")
        ? "text/javascript"
        : relative.endsWith(".css")
          ? "text/css"
          : relative.endsWith(".svg")
            ? "image/svg+xml"
            : relative.endsWith(".json")
              ? "application/json"
              : "text/html; charset=utf-8";
      res.writeHead(200, { "content-type": type });
      res.end(readFileSync(file));
      return;
    }
  }
  // Client-side routes (e.g. /app/fleet) have no asset file: fall back to the SPA shell.
  if (!/\.[a-z0-9]+$/i.test(relative)) {
    for (const rootDir of roots) {
      const file = join(rootDir, "index.html");
      if (existsSync(file) && statSync(file).isFile()) {
        res.writeHead(200, { "content-type": "text/html; charset=utf-8" });
        res.end(readFileSync(file));
        return;
      }
    }
  }
  // Keep the control plane navigable even when optional Mission Control
  // frontend dependencies are unavailable. A real built asset always wins
  // above; this bounded shell preserves the API entry point and gives the
  // operator an actionable diagnostic instead of a misleading 404.
  const fallback = `<!doctype html>
<html lang="en">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <title>Mission Control</title>
    <style>
      :root { color-scheme: dark; font-family: system-ui, sans-serif; }
      body { margin: 0; min-height: 100vh; background: #10131a; color: #e7eaf0; }
      main { max-width: 760px; margin: 12vh auto; padding: 32px; }
      h1 { margin-bottom: 8px; }
      code { color: #a7f3d0; }
      .card { border: 1px solid #303746; border-radius: 12px; padding: 20px; background: #171b24; }
    </style>
  </head>
  <body>
    <main id="root">
      <h1>Mission Control</h1>
      <div class="card">
        <p>The dashboard API is online, but the optional frontend bundle is not installed.</p>
        <p>Install dependencies and rebuild with <code>npm --prefix packages/mission-control install && npm run build:mission-control</code>.</p>
      </div>
    </main>
  </body>
</html>`;
  res.writeHead(200, { "content-type": "text/html; charset=utf-8" });
  res.end(fallback);
}

function timingSafeEqualStr(a: string, b: string): boolean {
  const ab = Buffer.from(a);
  const bb = Buffer.from(b);
  if (ab.length !== bb.length) return false;
  return timingSafeEqual(ab, bb);
}

